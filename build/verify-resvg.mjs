// Build gate: proves @resvg/resvg-js can actually rasterise on the machine running the
// build. This is a gate, not a fallback — the share-card and icon steps have no
// software renderer to fall back to, so a failure here must stop the build (C-16).
import fs from 'node:fs';

const PNG_MAGIC = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);

const FAIL = (why) => {
  throw new Error(
    `@resvg/resvg-js could not load a native binary on this platform ` +
      `(${process.platform}-${process.arch}). The share-card and icon steps cannot run. ` +
      `Ensure @resvg/resvg-js-linux-x64-gnu is present in package-lock.json — a macOS-only ` +
      `install is a launch-day failure, not a build-day one. [${why}]`
  );
};

export async function verifyResvg() {
  // 1 — lockfile assertion. Honest scope: npm >= 7 records all twelve platform variants
  //     on any normal install, so this passes unconditionally in the common case. It
  //     guards only against `--omit=optional`, `optional=false` in .npmrc, and lockfiles
  //     regenerated by a tool that prunes. It is NOT the C-16 mitigation.
  const lock = fs.readFileSync(new URL('../package-lock.json', import.meta.url), 'utf8');
  if (!lock.includes('@resvg/resvg-js-linux-x64-gnu')) FAIL('lockfile');

  // 2 — load assertion. This and the render assertion are the real C-16 mitigation, and
  //     only when Cloudflare's image runs them. Green on macOS proves nothing about
  //     Cloudflare until Cloudflare runs it.
  let Resvg;
  try {
    ({ Resvg } = await import('@resvg/resvg-js'));
  } catch {
    FAIL('load');
  }

  // 3 — render assertion: a binary can load and still fail to rasterise.
  const probe =
    '<svg xmlns="http://www.w3.org/2000/svg" width="4" height="4">' +
    '<rect width="4" height="4" fill="#161615"/></svg>';
  // loadSystemFonts: false keeps the render independent of whatever fonts the build
  // image happens to have, and is ~8x faster.
  const png = new Resvg(probe, { font: { loadSystemFonts: false } }).render().asPng();
  if (png.length < 8 || !png.subarray(0, 8).equals(PNG_MAGIC)) FAIL('render');
}
